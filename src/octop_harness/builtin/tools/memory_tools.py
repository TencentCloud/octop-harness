"""LLM tool functions for the memory system.

These are registered as agent tools at construction time. They use
``langchain_core.tools.tool`` to produce ``StructuredTool`` instances.

The agent exposes service-backed tools:

* ``memory_search(query, max_results)`` routes through the
  :class:`MemoryService` ranker (atom + page + raw).
* ``memory_get(path, start, lines)`` resolves a virtual path returned by
  ``memory_search``.
* ``memory_save(content, topic, kind)`` explicitly persists a typed memory through
  :meth:`MemoryService.save`.

``MEMORY.md`` is user-maintained strong memory, loaded in full into chat
context. Remember requests use ``memory_save`` and never edit that file.
Background distillation continues to extract facts from captured conversation.

Each tool wraps the underlying service call in a broad ``except`` so that
storage / DB faults degrade into a human-readable string instead of
crashing the agent turn or leaking a stack trace into the conversation.
"""

from __future__ import annotations

import inspect
import json
import logging
import re
from typing import TYPE_CHECKING, Literal

from langchain_core.tools import StructuredTool, tool

if TYPE_CHECKING:
    from octop_memory import MemoryService

logger = logging.getLogger(__name__)

_IMAGE_BLOCK_TYPES = {"image", "image_url", "input_image"}
_IMAGE_PAYLOAD_FIELDS = {"base64", "data", "file_id", "image_url", "source", "url", "workspace_path"}
_IMAGE_ONLY_CAPTIONS = {"User sent an image.", "用户发送了图片。", "[image]"}
_BLOCK_TYPE_PREFIX = re.compile(r'^\{\s*"type"\s*:\s*"([a-z_]+)')
_IMAGE_URL_PREFIX = re.compile(r'^\{\s*"image_url"\s*:')


def _is_dumped_image(line: str) -> bool:
    if not line.startswith("{"):
        return False
    try:
        block = json.loads(line)
    except (ValueError, RecursionError):
        # Search can clip the raw snippet before it reaches this tool.
        if _IMAGE_URL_PREFIX.match(line):
            return True
        match = _BLOCK_TYPE_PREFIX.match(line)
        if match is None:
            return False
        kind = match[1]
        return kind in _IMAGE_BLOCK_TYPES or (
            line.endswith("…")
            and kind.startswith(("ima", "input_ima"))
            and any(image_type.startswith(kind) for image_type in _IMAGE_BLOCK_TYPES)
        )
    if not isinstance(block, dict):
        return False
    kind = block.get("type")
    return isinstance(kind, str) and kind in _IMAGE_BLOCK_TYPES and bool(_IMAGE_PAYLOAD_FIELDS.intersection(block))


def _strip_raw_images(snippet: str, *, preserve_lines: bool = False) -> str:
    # Memory capture writes each non-text content block on its own JSON line.
    result: list[str] = []
    removed_image = False
    for line in snippet.split("\n"):
        if _is_dumped_image(line.strip()):
            removed_image = True
            if preserve_lines:
                result.append("")
        else:
            result.append(line)
    text = "\n".join(result)
    return "" if removed_image and text.strip() in _IMAGE_ONLY_CAPTIONS else text


def _filter_raw_excerpt(excerpt: str, *, start: int | None) -> str:
    # Count usable text in the body, excluding metadata generated by Memory.
    header = ""
    if start in (None, 1) and (excerpt == "---" or excerpt.startswith("---\nid: ")):
        prefix, delimiter, excerpt = excerpt.partition("\n---\n")
        header = prefix + delimiter
    text = _strip_raw_images(excerpt, preserve_lines=True)
    body = text.strip()
    if not body or body in _IMAGE_ONLY_CAPTIONS:
        return ""
    return header + text


def _format_memory_get(result: object, *, path: str, start: int | None) -> str:
    if not isinstance(result, dict):
        return str(result)
    if result.get("error"):
        return f"memory_get error: {result.get('error')}"
    content = result.get("content")
    if path.startswith("raw/") or result.get("kind") == "raw":
        if isinstance(content, str):
            content = _filter_raw_excerpt(content, start=start)
        else:
            excerpt = result.get("excerpt")
            filtered = _filter_raw_excerpt(excerpt, start=start) if isinstance(excerpt, str) else ""
            content = str({**result, "excerpt": filtered}) if filtered else ""
        return content or "No usable memory content."
    return content if isinstance(content, str) else str(result)


def build_memory_tools(service: MemoryService) -> list[StructuredTool]:
    """Build :class:`MemoryService`-backed LLM tools.

    Exposes recall and explicit persistence tools:

    * ``memory_search(query, max_results)`` — ranked hits across
      atom / entity_page / raw. Each hit carries a virtual ``path`` you
      can pass to ``memory_get``.
    * ``memory_get(path, start, lines)`` — resolve a virtual path to its
      source markdown excerpt.

    * ``memory_save(content, topic, kind)`` — persist canonical memory through the
      service, independently of the user-maintained ``MEMORY.md``.

    Args:
        service: A :class:`MemoryService` to bind the tools to.
    """
    save_parameters = inspect.signature(service.save).parameters
    supports_kind = "kind" in save_parameters or any(
        parameter.kind == inspect.Parameter.VAR_KEYWORD for parameter in save_parameters.values()
    )

    @tool
    def memory_search(query: str, max_results: int = 5) -> str:
        """Search the agent's memory across atoms, entity pages, raw events.

        Use this when the user references something that happened in a
        previous turn or session, or asks about a fact / preference /
        decision they expect the agent to remember. Raw hits show their text;
        image-only hits are skipped.

        Args:
            query: Natural-language search query.
            max_results: Cap on returned hits (default 5, max ~20).
        """
        try:
            result = service.search(query, max_results=max_results)
        except Exception as exc:  # pragma: no cover - storage / ranker / model fault; pylint: disable=broad-except
            logger.warning("memory_search failed: %s", exc, exc_info=True)
            return f"memory_search failed: {exc.__class__.__name__}"
        hits = result.get("hits", []) if isinstance(result, dict) else []
        warning = result.get("warning") if isinstance(result, dict) else None
        if not hits:
            if warning:
                return str(warning)
            empty_reason = result.get("empty_reason") if isinstance(result, dict) else None
            return f"No matching memory entries. ({empty_reason or 'empty'})"
        lines: list[str] = []
        for h in hits:
            path = h.get("path", "?")
            layer = h.get("layer") or "?"
            snippet = (h.get("snippet") or "").strip()
            if layer == "raw":
                snippet = _strip_raw_images(snippet).strip()
                if not snippet:
                    continue
            snippet = snippet.replace("\n", " ")
            if len(snippet) > 200:
                snippet = snippet[:200] + "..."
            lines.append(f"- [{layer}] {path}\n  {snippet}")
        if not lines:
            return str(warning or "No matching memory entries. (empty)")
        if warning:
            lines.append(str(warning))
        return "Memory hits:\n" + "\n".join(lines)

    @tool
    def memory_get(path: str, start: int | None = None, lines: int | None = None) -> str:
        """Resolve a virtual memory path to its source text.

        Pass a path returned by ``memory_search`` (e.g.
        ``atom/<id>.md`` / ``page/<entity>.md`` / ``raw/<date>/<id>.md``)
        to read the underlying markdown. Raw excerpts omit image blocks.

        Args:
            path: The virtual path string from a ``memory_search`` hit.
            start: Optional 1-based line number to start at.
            lines: Optional number of lines to return.
        """
        try:
            result = service.get(path, start=start, lines=lines)
        except Exception as exc:  # pragma: no cover - storage / IO fault; pylint: disable=broad-except
            logger.warning("memory_get failed: %s", exc, exc_info=True)
            return f"memory_get failed: {exc.__class__.__name__}"
        return _format_memory_get(result, path=path, start=start)

    @tool
    def memory_save(
        content: str,
        topic: str | None = None,
        kind: Literal["Fact", "Preference", "Decision", "Task"] = "Fact",
    ) -> str:
        """Save a durable memory with its semantic kind to octop-memory.

        Use when the user asks you to remember something. Store one concise
        memory per call; choose its kind in this tool call, without another
        model request. Only confirm remembering after this tool succeeds.
        Do not read USER.md or MEMORY.md to save a memory. Those files stay
        in the session snapshot, and document reconciliation runs later.

        Args:
            content: The memory to save, preserving its scope and qualifiers.
            topic: Optional topic used to organize the memory.
            kind: Preference for stable likes/communication habits, Decision
                for an agreed choice, Task for a commitment/to-do, Fact for
                other factual knowledge or uncertain classification. A Task
                does not create a scheduled reminder. Topic is not a kind.
                Do not retry a typed save as Fact after an upgrade error.
        """
        if not content.strip():
            return "memory_save failed: content is empty"
        if kind != "Fact" and not supports_kind:
            return "memory_save failed: upgrade octop-memory to a version supporting MemoryService.save(kind=...)"
        try:
            if kind == "Fact":
                service.save(content.strip(), topic=topic)
            else:
                service.save(content.strip(), topic=topic, kind=kind)
        except Exception as exc:  # pragma: no cover - fail softly at the tool boundary; pylint: disable=broad-except
            logger.warning("memory_save failed: %s", exc, exc_info=True)
            return f"memory_save failed: {exc.__class__.__name__}"
        return "Memory saved to octop-memory."

    return [memory_search, memory_get, memory_save]  # type: ignore[list-item]


__all__ = ["build_memory_tools"]
